import { ActiveModule, Language, BullyingAnalysisResult } from '../types';

interface GenerateOptions {
  module: ActiveModule;
  prompt: string;
  context?: string;
  userGrade?: string;
  language?: Language;
  apiKey?: string;
  explanationLevel?: 'kid' | 'standard' | 'deep';
}

interface GenerateResponse {
  text: string;
  isCrisis?: boolean;
}

// Crisis keywords in Kazakh & Russian
